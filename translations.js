function setLanguage(lang) {
  currentLang = lang;
  document.querySelectorAll('#settings-panel .lang-btn').forEach(b => b.classList.remove('active'));
  const btn = document.getElementById('lang-' + lang);
  if (btn) btn.classList.add('active');
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    el.textContent = t(key);
  });
  if (currentRole === 'customer') {
    cRenderProducts(products, 'c-productGrid');
    cRenderFavorites();
    cRenderFarms();
    cRenderOrders();
  }
  const langName = lang==='en'?'English':lang==='ml'?'മലയാളം':lang==='hi'?'हिन्दी':'தமிழ்';
  showToast('Language · ' + langName);
}

function setFarmerLanguage(lang) {
  currentFarmerLang = lang;
  // Sync shared lang too so product names etc. align
  currentLang = lang;
  document.querySelectorAll('#farmer-lang-panel .lang-btn').forEach(b => b.classList.remove('active'));
  const btn = document.getElementById('f-lang-' + lang);
  if (btn) btn.classList.add('active');
  // Update data-ft elements
  document.querySelectorAll('[data-ft]').forEach(el => {
    const key = el.getAttribute('data-ft');
    el.textContent = ft(key);
  });
  if (currentRole === 'farmer') {
    fRenderProducts();
    fRenderOrders();
    fRenderInventory();
  }
  const langName = lang==='en'?'English':lang==='ml'?'മലയാളം':lang==='hi'?'हिन्दी':'தமிழ்';
  showToast('Language · ' + langName);
}
